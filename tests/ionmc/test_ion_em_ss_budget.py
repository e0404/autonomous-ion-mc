def test_window_kernels_closed_form_and_series_agree() -> None:
    """int_-W^W x^k cos(eta x) dx: series = closed form at the switch; k = 4 by quadrature."""
    w = 1.3
    eps = 1e-9
    for k, u_sw in ((2, 0.05), (4, 0.5)):
        lo = S._g_window(np.array([(u_sw - eps) / w]), w, k)[0]
        hi = S._g_window(np.array([(u_sw + eps) / w]), w, k)[0]
        assert lo == pytest.approx(hi, rel=1e-9)
    x = np.linspace(-w, w, 200001)
    for eta in (0.2, 3.0, 17.0):
        direct = np.trapezoid(x**4 * np.cos(eta * x), x)
        assert S._g_window(np.array([eta]), w, 4)[0] == pytest.approx(direct, rel=1e-8, abs=1e-12)


def test_moments_reproduce_truncated_gaussian_and_factorise() -> None:
    """Gaussian characteristic function: 1-D moments = closed form; 2-D joint moments factorise."""
    sigma = 1.0e-3
    w = 2.5 * sigma

    def char(e: Any) -> Any:
        return np.exp(-0.5 * (sigma * e) ** 2)

    p0, m2, m4 = S.windowed_moments_char(char, w, sigma)
    gp, gm2, gm4 = S.gauss_window_moments(sigma, w)
    assert (p0, m2, m4) == pytest.approx((gp, gm2, gm4), rel=1e-9)
    q00, q20, q22 = S.windowed_joint_char(char, w, sigma)
    assert (q00, q20, q22) == pytest.approx((p0 * p0, p0 * m2, m2 * m2), rel=1e-6)


def test_rms_standard_error_gaussian_limits() -> None:
    """Untruncated Gaussian: rel SE of the rms = 1/sqrt(2N) (one projection), 1/sqrt(4N) pooled."""
    gp, gm2, gm4 = S.gauss_window_moments(1.0, 40.0)
    n = 2.0e4
    assert S.rms_rel_se(gp, gm2, gm4, n) == pytest.approx(1.0 / math.sqrt(2.0 * n), rel=1e-9)
    pooled = S.rms_rel_se(gp, gm2, gm4, n, (gp * gp, gp * gm2, gm2 * gm2))
    assert pooled == pytest.approx(1.0 / math.sqrt(4.0 * n), rel=1e-9)


