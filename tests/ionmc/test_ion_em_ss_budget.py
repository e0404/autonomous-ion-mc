def test_omega_closed_form_matches_direct_quadrature() -> None:
    """Omega of one screened species: closed form vs the defining integral by quadrature."""
    c2, a = 2.0e-6, 1.0e-5
    # eta a = 0.3, 1 (series branch) and 4 (integral branch); the theta > 1e-2 tail is < 1e-5
    eta = np.array([3.0e4, 1.0e5, 4.0e5])
    th = np.concatenate(([0.0], np.logspace(-9, -2, 40001)))
    integ = th / (th**2 + a * a) ** 2
    direct = []
    for e in eta:
        f = integ * (1.0 - S.bessel_j0(e * th, chunk=2000))
        direct.append(2.0 * c2 * np.trapezoid(f, th))
    closed = S.omega(eta, [(c2, a, None)])
    np.testing.assert_allclose(closed, np.array(direct), rtol=1e-4)


def test_omega_limits_moliere_form_and_collision_number() -> None:
    """Small eta: Moliere's (chi_c^2 eta^2/4)(-ln(a^2 eta^2/4) + 1 - 2 C_E); large: chi_c^2/a^2."""
    c2, a = 3.0e-6, 2.0e-5
    eta = np.array([1.0])
    moliere = c2 * eta**2 / 4.0 * (-np.log(a * a * eta**2 / 4.0) + 1.0 - 2.0 * S.EULER_GAMMA)
    np.testing.assert_allclose(S.omega(eta, [(c2, a, None)]), moliere, rtol=1e-8)
    big = S.omega(np.array([1.0e8]), [(c2, a, None)])[0]
    assert big == pytest.approx(c2 / a**2, rel=1e-6)


def test_windowed_transform_reproduces_truncated_gaussian() -> None:
    """exp(-sigma^2 eta^2/2) through the windowed transform = the closed-form truncated Gaussian."""
    sigma = 1.0e-3
    for k in (1.0, 2.5, 4.0):
        w = k * sigma
        rms, p0 = S.windowed_rms_char(lambda e: np.exp(-0.5 * (sigma * e) ** 2), w, sigma)
        assert rms == pytest.approx(S.gauss_windowed(sigma, w), rel=1e-6)
        assert p0 == pytest.approx(math.erf(k / math.sqrt(2.0)), rel=1e-6)


