def test_bias_terms_vanish_for_equal_models_and_telescope() -> None:
    r = S.case_widths(2, 150.0)
    same = {k: r["gauss"] for k in ("gauss", "MF", "TF_nocorr", "TF_corr", "U_corr")}
    same["th"] = r["th"]
    other = dict(same)
    t = S.pair_terms(same, other)
    assert all(v == 0.0 for v in t.values())
    # identical ions: every term vanishes
    t = S.pair_terms(r, r)
    assert all(v == 0.0 for v in t.values())
    # the decomposition telescopes to the total bias
    rb = S.case_widths(6, 150.0)
    t = S.pair_terms(r, rb)
    prod = (1 + t["estimator"]) * (1 + t["electrons"]) * (1 + t["corr"]) * (1 + t["radius"])
    assert prod - 1.0 == pytest.approx(t["bias"], abs=1e-14)


def test_corr_and_radius_switches_are_neutral_where_they_should_be() -> None:
    """corr = 1 when switched off; Thomas-Fermi radius is independent of the projectile z."""
    m, p, b2, pv = S.kinematics(6, 150.0)
    a_tf_c = [a for _, a, _ in S.species_ion_path(6, p, b2, "tf", False)]
    m2, p2, b22, pv2 = S.kinematics(2, 150.0)
    a_tf_he = [a for _, a, _ in S.species_ion_path(2, p2, b22, "tf", False)]
    # at equal velocity a ~ x/p sqrt(1.13 + 3.76 alpha'^2): only the Born term differs with z
    for (zt, _, _), ac, ah in zip(S.WATER, a_tf_c, a_tf_he, strict=True):
        born_c = 1.13 + 3.76 * (6 * zt * S.ALPHA) ** 2 / b2
        born_he = 1.13 + 3.76 * (2 * zt * S.ALPHA) ** 2 / b22
        assert (ac * p) / (ah * p2) == pytest.approx(math.sqrt(born_c / born_he), rel=1e-12)


