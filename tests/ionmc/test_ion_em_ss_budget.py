def test_gate_is_the_plan_tost_rule() -> None:
    """Round V3-008-5 (Codex REVIEW-6a14f4ec finding 2): PASS iff |x - r| + 1.645 sigma <= 3 %."""
    assert S.TOLERANCE_PCT == 3.0 and S.SIGMA_MAX_PCT == 1.0 and S.Z_TOST == 1.645
    # the round V3-008-4 example: a 2.99 % deviation with sigma 0.9 % now FAILS (bound 4.47 %)
