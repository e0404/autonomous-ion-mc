def test_one_minus_xk1_series_and_integral_agree_and_small_x_asymptote() -> None:
    # 1 - 2 K1(2) = 0.7202682 (K1(2) = 0.1398659, A-S Table 9.8); series below, integral at 2
    v = S.one_minus_xk1(np.array([1.9999999, 2.0]))
    assert v == pytest.approx([0.72026824, 0.72026824], abs=2e-7)
    x = 1e-3
    asym = x * x / 2.0 * (math.log(2.0 / x) + 0.5 - S.EULER_GAMMA)
    assert S.one_minus_xk1(np.array([x]))[0] == pytest.approx(asym, rel=1e-6)


