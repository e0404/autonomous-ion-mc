def test_omega_closed_form_matches_direct_quadrature() -> None:
    """Omega of one screened species: closed form vs the defining integral by quadrature."""
    c2, a = 2.0e-6, 1.0e-5
    # eta a = 0.3, 1 (series branch) and 4 (integral branch); the theta > 1e-2 tail is < 1e-5
    eta = np.array([3.0e4, 1.0e5, 4.0e5])
    th = np.concatenate(([0.0], np.logspace(-9, -2, 40001)))
    integ = th / (th**2 + a * a) ** 2
    direct = []
    for e in eta:
        f = integ * (1.0 - S.bessel_j0(e * th, chunk=2000))
        direct.append(2.0 * c2 * np.trapezoid(f, th))
    closed = S.omega(eta, [(c2, a, None)])
    np.testing.assert_allclose(closed, np.array(direct), rtol=1e-4)


def test_omega_limits_moliere_form_and_collision_number() -> None:
    """Small eta: Moliere's (chi_c^2 eta^2/4)(-ln(a^2 eta^2/4) + 1 - 2 C_E); large: chi_c^2/a^2."""
    c2, a = 3.0e-6, 2.0e-5
    eta = np.array([1.0])
    moliere = c2 * eta**2 / 4.0 * (-np.log(a * a * eta**2 / 4.0) + 1.0 - 2.0 * S.EULER_GAMMA)
    np.testing.assert_allclose(S.omega(eta, [(c2, a, None)]), moliere, rtol=1e-8)
    big = S.omega(np.array([1.0e8]), [(c2, a, None)])[0]
    assert big == pytest.approx(c2 / a**2, rel=1e-6)


def test_windowed_transform_reproduces_truncated_gaussian() -> None:
    """exp(-sigma^2 eta^2/2) through the windowed transform = the closed-form truncated Gaussian."""
    sigma = 1.0e-3
    for k in (1.0, 2.5, 4.0):
        w = k * sigma
        rms, p0 = S.windowed_rms_char(lambda e: np.exp(-0.5 * (sigma * e) ** 2), w, sigma)
        assert rms == pytest.approx(S.gauss_windowed(sigma, w), rel=1e-6)
        assert p0 == pytest.approx(math.erf(k / math.sqrt(2.0)), rel=1e-6)


def test_gauss_windowed_wide_window_limit() -> None:
    assert S.gauss_windowed(1.0, 40.0) == pytest.approx(1.0, rel=1e-12)


def test_bias_terms_vanish_for_equal_models_and_telescope() -> None:
    r = S.case_widths(2, 150.0)
    same = {k: r["gauss"] for k in ("gauss", "MF", "TF_nocorr", "TF_corr", "U_corr")}
    same["th"] = r["th"]
    other = dict(same)
    t = S.pair_terms(same, other)
    assert all(v == 0.0 for v in t.values())
    # identical ions: every term vanishes
    t = S.pair_terms(r, r)
    assert all(v == 0.0 for v in t.values())
    # the decomposition telescopes to the total bias
    rb = S.case_widths(6, 150.0)
    t = S.pair_terms(r, rb)
    prod = (1 + t["estimator"]) * (1 + t["electrons"]) * (1 + t["corr"]) * (1 + t["radius"])
    assert prod - 1.0 == pytest.approx(t["bias"], abs=1e-14)


def test_corr_and_radius_switches_are_neutral_where_they_should_be() -> None:
    """corr = 1 when switched off; Thomas-Fermi radius is independent of the projectile z."""
    m, p, b2, pv = S.kinematics(6, 150.0)
    a_tf_c = [a for _, a, _ in S.species_ion_path(6, p, b2, "tf", False)]
    m2, p2, b22, pv2 = S.kinematics(2, 150.0)
    a_tf_he = [a for _, a, _ in S.species_ion_path(2, p2, b22, "tf", False)]
    # at equal velocity a ~ x/p sqrt(1.13 + 3.76 alpha'^2): only the Born term differs with z
    for (zt, _, _), ac, ah in zip(S.WATER, a_tf_c, a_tf_he, strict=True):
        born_c = 1.13 + 3.76 * (6 * zt * S.ALPHA) ** 2 / b2
        born_he = 1.13 + 3.76 * (2 * zt * S.ALPHA) ** 2 / b22
        assert (ac * p) / (ah * p2) == pytest.approx(math.sqrt(born_c / born_he), rel=1e-12)


def test_equal_velocity_kinematics() -> None:
    for z in (2, 6, 8):
        m, p, b2, pv = S.kinematics(z, 250.0)
        tp = S.proton_energy_equal_velocity(z, 250.0)
        _, pp, b2p, _ = S.kinematics(1, tp)
        assert b2p == pytest.approx(b2, rel=1e-12)


