BUNDLES = sorted(d for d in TOPAS.iterdir() if d.is_dir() and d.name.startswith("v5ss-"))
PARTS = [d for d in BUNDLES if re.search(r"-part\d$", d.name)]


def _native(d, key):
    m = re.findall(rf"^{re.escape(key)} = (.+)$", (d / "input.txt").read_text(), re.M)
    assert len(m) == 1, (d.name, key)
    return m[0].strip()


def test_bundle_set():
    assert len(BUNDLES) == 33 and len(PARTS) == 32
    assert gen.BLOCK1_PARTS == (0, 1) and gen.EVIDENCE_PARTS == (2, 3)
    assert gen.PARTS == (0, 1, 2, 3)
    assert [d.name for d in BUNDLES] == gen.bundle_names()
    assert SMOKE in [d.name for d in BUNDLES]
    for d in PARTS:
        assert "-r2-" not in d.name
        m = re.fullmatch(r"v5ss-(he|carbon|oxygen)-water-(\d+)mevu-case(\d\d)-part([0-3])", d.name)
        assert m, d.name
        assert ION[int(m.group(3))] == m.group(1)


def test_regeneration_is_byte_identical_and_idempotent(tmp_path):
    made = gen.generate(tmp_path)
    assert sorted(nm for nm, _ in made) == [d.name for d in BUNDLES]
    for nm, _ in made:
        for f in ("case.json", "input.txt"):
            assert (TOPAS / nm / f).read_bytes() == (tmp_path / nm / f).read_bytes(), nm
    assert gen.manifest_text(tmp_path) == MANIFEST.read_text()
    gen.generate(tmp_path)
    assert gen.manifest_text(tmp_path) == MANIFEST.read_text()


def test_manifest_matches_files():
    m = json.loads(MANIFEST.read_text())
    assert m["schema"] == "ionmc-v5ss-frozen-bundles-1"
    assert m["bundle_count"] == 33 and m["file_count"] == 66
    for d in BUNDLES:
        for f in ("case.json", "input.txt"):
            assert m["bundles"][d.name][f] == hashlib.sha256((d / f).read_bytes()).hexdigest()


def test_block1_entries_byte_identical():
    """The 16 block-1 (part 0/1) manifest entries equal those committed before block 2 existed."""
    frozen = json.loads(BLOCK1_ENTRIES.read_text())
    assert len(frozen) == 16
    assert all(re.search(r"-part[01]$", n) for n in frozen)
    m = json.loads(MANIFEST.read_text())["bundles"]
    assert {n: e for n, e in m.items() if re.search(r"-part[01]$", n)} == frozen


def test_block2_differs_from_block1_only_in_seed_and_part_wording():
    for case_no in SS_CASES:
        for b2, b1 in ((2, 0), (3, 1)):
            new_d = TOPAS / gen.bundle_name(case_no, b2)
            old_d = TOPAS / gen.bundle_name(case_no, b1)
            new_c = json.loads((new_d / "case.json").read_text())
            old_c = json.loads((old_d / "case.json").read_text())
            assert new_c["seeds"] == [20619000 + 100 * b2 + case_no]
            assert old_c["seeds"] == [20619000 + 100 * b1 + case_no]
            assert {k for k in new_c if new_c[k] != old_c[k]} == {"seeds", "rationale"}
            old_seed, new_seed = old_c["seeds"][0], new_c["seeds"][0]
            want_rat = old_c["rationale"].replace(
                f"part {b1} of parts 0-1, seed 20619000 + 100*{b1} + {case_no} = {old_seed}",
                f"part {b2} of parts 2-3 (evidence block 2), seed 20619000 + 100*{b2} + "
                f"{case_no} = {new_seed}",
            )
            assert new_c["rationale"] == want_rat != old_c["rationale"]
            new_l = (new_d / "input.txt").read_text().split("\n")
            old_l = (old_d / "input.txt").read_text().split("\n")
            assert len(new_l) == len(old_l)
            diff = [i for i, (a, b) in enumerate(zip(new_l, old_l, strict=True)) if a != b]
            assert [new_l[i].split(" = ")[0] for i in diff[1:]] == ["i:Ts/Seed"]
            assert new_l[diff[1]] == f"i:Ts/Seed = {new_seed}"
            assert diff[0] == 0
            assert new_l[0] == old_l[0].replace(
                f"part {b1} of parts 0-1 ",
                f"part {b2} of parts 2-3 (evidence block 2; amendment V5-SS-B2 of 2026-11-15; "
                "parts 0-1 are the exploratory block 1) ",
            )


