"""Guards for the V5-SS TOPAS bundles (pure python, CI-fast).

The bundles ``validation/reference_cases/topas/v5ss-*`` and their frozen manifest are generated by
``validation/scripts/ion_em/gen_ss_bundles.py`` (single source); the r2 bundles and the r2 frozen
manifest stay byte-identical.
"""

import hashlib
import importlib.util
import json
import re
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
TOPAS = ROOT / "validation" / "reference_cases" / "topas"
MANIFEST = TOPAS / "v5ss-frozen-manifest.json"
R2_MANIFEST = ROOT / "validation" / "results" / "transport" / "v8r2-topas" / "frozen-bundles.json"
R2_MANIFEST_SHA256 = "f5e39fe6c7c1c846070e34970024717d86c36dd04b8b287b993a07947856400d"
SS_CASES = (22, 25, 26, 27, 28, 29, 30, 31)
ION = {22: "he", 25: "carbon", 26: "oxygen", 27: "carbon", 28: "he", 29: "carbon", 30: "oxygen",
       31: "oxygen"}  # fmt: skip
SMOKE = "v5ss-helium-water-250mevu-scorer-smoke"


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


gen = _load("gen_ss_bundles", ROOT / "validation" / "scripts" / "ion_em" / "gen_ss_bundles.py")
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
from infrastructure.experiment_v3 import reference  # noqa: E402

BUNDLES = sorted(d for d in TOPAS.iterdir() if d.is_dir() and d.name.startswith("v5ss-"))
PARTS = [d for d in BUNDLES if re.search(r"-part\d$", d.name)]


def _native(d, key):
    m = re.findall(rf"^{re.escape(key)} = (.+)$", (d / "input.txt").read_text(), re.M)
    assert len(m) == 1, (d.name, key)
    return m[0].strip()


def test_bundle_set():
    assert len(BUNDLES) == 17 and len(PARTS) == 16
    assert [d.name for d in BUNDLES] == gen.bundle_names()
    assert SMOKE in [d.name for d in BUNDLES]
    for d in PARTS:
        assert "-r2-" not in d.name
        m = re.fullmatch(r"v5ss-(he|carbon|oxygen)-water-(\d+)mevu-case(\d\d)-part([01])", d.name)
        assert m, d.name
        assert ION[int(m.group(3))] == m.group(1)


def test_regeneration_is_byte_identical_and_idempotent(tmp_path):
    made = gen.generate(tmp_path)
    assert sorted(nm for nm, _ in made) == [d.name for d in BUNDLES]
    for nm, _ in made:
        for f in ("case.json", "input.txt"):
            assert (TOPAS / nm / f).read_bytes() == (tmp_path / nm / f).read_bytes(), nm
    assert gen.manifest_text(tmp_path) == MANIFEST.read_text()
    gen.generate(tmp_path)
    assert gen.manifest_text(tmp_path) == MANIFEST.read_text()


def test_manifest_matches_files():
    m = json.loads(MANIFEST.read_text())
    assert m["schema"] == "ionmc-v5ss-frozen-bundles-1"
    assert m["bundle_count"] == 17 and m["file_count"] == 34
    for d in BUNDLES:
        for f in ("case.json", "input.txt"):
            assert m["bundles"][d.name][f] == hashlib.sha256((d / f).read_bytes()).hexdigest()


def test_r2_manifest_unchanged():
    assert hashlib.sha256(R2_MANIFEST.read_bytes()).hexdigest() == R2_MANIFEST_SHA256
    assert not any(n.startswith("v5ss-") for n in json.loads(R2_MANIFEST.read_text())["bundles"])


@pytest.mark.parametrize("d", BUNDLES, ids=lambda d: d.name)
def test_case_validates_and_native_lines(d):
    case = json.loads((d / "case.json").read_text())
    reference.validate_case(case)
    r2_keys = json.loads(
        (TOPAS / "he-water-150mevu-r2-lat-em-part4" / "case.json").read_text()
    ).keys()
    assert list(case) == list(r2_keys)
    assert int(_native(d, "i:Ts/Seed")) == case["seeds"][0]
    assert int(_native(d, "i:So/Beam/NumberOfHistoriesInRun")) == case["histories"]
    assert _native(d, "d:Ph/Default/CutForAllParticles") == "0.05 mm"
    assert _native(d, "d:Ph/Default/CutForElectron") == "1 km"
    assert _native(d, "d:Ph/Default/EMRangeMax") == "10 GeV"
    assert _native(d, "i:Ts/MaxStepNumber") == "100000000"
    assert _native(d, "sv:Ph/Default/Modules") == '1 "g4em-standard_SS"'
    assert _native(d, "b:Ph/ListProcesses") == '"True"'
    text = (d / "input.txt").read_text()
    assert re.findall(r"^s:Sc/(\w+)/Quantity = (.+)$", text, re.M) == [("SSExit", '"PhaseSpace"')]
    assert _native(d, "s:Sc/SSExit/Surface") == '"Water/ZPlusSurface"'
    assert _native(d, "s:Sc/SSExit/OutputType") == '"ASCII"'
    assert case["expected_outputs"] == ["ss_exit.phsp", "ss_exit.header"]


def test_seeds_histories_and_particles():
    for d in PARTS:
        m = re.search(r"case(\d\d)-part(\d)$", d.name)
        case_no, part = int(m.group(1)), int(m.group(2))
        c = json.loads((d / "case.json").read_text())
        assert c["seeds"] == [20619000 + 100 * part + case_no]
        assert c["histories"] == 30000
        ion, e_u, a, particle = gen.CASES[case_no]
        assert _native(d, "s:So/Beam/BeamParticle") == f'"{particle}"'
        assert _native(d, "d:So/Beam/BeamEnergy") == f"{a * e_u} MeV"
    totals = {}
    for d in PARTS:
        k = int(re.search(r"case(\d\d)", d.name).group(1))
        totals[k] = totals.get(k, 0) + json.loads((d / "case.json").read_text())["histories"]
    assert totals == dict.fromkeys(SS_CASES, 60000)
    assert gen.CASES[22][3] == gen.CASES[28][3] == "alpha"  # as the r2 He bundles
    assert _native(TOPAS / "he-water-150mevu-r2-lat-em-part4", "s:So/Beam/BeamParticle") == (
        '"alpha"'
    )


def test_smoke_bundle():
    d = TOPAS / SMOKE
