"""Guards for the V3-008 plan revision 2 TOPAS bundles (pure python, CI-fast).

The bundles under validation/reference_cases/topas/*-r2-* are generated by
validation/scripts/ion_em/gen_r2_bundles.py (single source); the recorded bundle-set digest is
validation/plans/v3-008/r2-topas-target.md appendix A.
"""

import importlib.util
import json
import re
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
TOPAS = ROOT / "validation" / "reference_cases" / "topas"
RECORDED_DIGEST = "9bd6f8023b4aa4b0bebbb21c5e237ea5a71c136dbc5243dbef5ef772c54a212f"
FULL_MODULES = [
    "g4em-standard_opt4",
    "g4h-phy_QGSP_BIC_HP",
    "g4decay",
    "g4h-elastic_HP",
    "g4stopping",
    "g4ion-QMD",
    "g4radioactivedecay",
]
SMOKE_RANGE = range(20600411, 20600424)


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


gen = _load("gen_r2_bundles", ROOT / "validation" / "scripts" / "ion_em" / "gen_r2_bundles.py")
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
from infrastructure.experiment_v3 import reference  # noqa: E402

BUNDLES = sorted(d for d in TOPAS.iterdir() if d.is_dir() and "-r2-" in d.name)


def test_bundle_count():
    assert len(BUNDLES) == 205


def test_regeneration_is_byte_identical_and_digest_matches(tmp_path):
    made = gen.generate(tmp_path)
    assert sorted(nm for nm, _ in made) == [d.name for d in BUNDLES]
    for nm, _ in made:
        for f in ("case.json", "input.txt"):
            assert (TOPAS / nm / f).read_bytes() == (tmp_path / nm / f).read_bytes(), f"{nm}/{f}"
    digest, nfiles = gen.bundle_set_digest(tmp_path)
    assert nfiles == 410
    assert digest == RECORDED_DIGEST
    assert gen.bundle_set_digest(TOPAS) == (RECORDED_DIGEST, 410)


@pytest.mark.parametrize("d", BUNDLES, ids=lambda d: d.name)
def test_case_validates(d):
    case = json.loads((d / "case.json").read_text())
    reference.validate_case(case)


def _seed(d):
    case = json.loads((d / "case.json").read_text())
    assert len(case["seeds"]) == 1
    return case["seeds"][0]


def test_seed_formula_and_uniqueness():
    seeds = {}
    for d in BUNDLES:
        seed = _seed(d)
        m = re.search(r"-part(\d+)$", d.name)
        if m:
            part = int(m.group(1))
            assert 0 <= part <= 15, d.name  # 16-19 reserved, never used
            case_no = seed - 20619000 - 100 * part
            assert 1 <= case_no <= 12, d.name
            assert seed == 20619000 + 100 * part + case_no
        else:
            assert d.name.endswith(("-timing-smoke", "-steps-verbose-smoke")), d.name
            assert seed in SMOKE_RANGE, d.name
        assert seed not in seeds, f"{d.name} shares seed with {seeds[seed]}"
        seeds[seed] = d.name
    assert len(seeds) == 205
    assert sorted(s for s in seeds if s in SMOKE_RANGE) == list(SMOKE_RANGE)


def _modules(d):
    text = (d / "input.txt").read_text()
    m = re.findall(r'^sv:Ph/Default/Modules = (\d+)((?: "[^"]+")+)\s*$', text, re.M)
    assert len(m) == 1, d.name
    n, rest = m[0]
    mods = re.findall(r'"([^"]+)"', rest)
    assert int(n) == len(mods)
    return mods


@pytest.mark.parametrize("d", BUNDLES, ids=lambda d: d.name)
def test_module_lists(d):
    mods = _modules(d)
    if "-full-" in d.name:
        assert mods == FULL_MODULES
    else:
        assert "-em-" in d.name
        assert mods == ["g4em-standard_opt4"]
