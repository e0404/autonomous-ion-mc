"""BGG and Barashenkov proton-nucleus and p-p elastic cross sections (decision 0041, slice C).

Acceptance Amendment 14 (b), implemented literally: "p+A (C, N, O, Ca and the decision-0041
surrogates), 1-250 MeV: sigma_el(E) = BGG/Barashenkov max(sigma_tot(n+A) - sigma_inel(p+A), 0).
The Barashenkov arrays are hand-transcribed from Geant4 11.4.2 `G4BarashenkovData.hh`. The rules
are linear interpolation in E and A^{2/3} interpolation for untabulated Z, with the BGG
low-energy rule below 14 MeV. The formulas are hand-re-implemented from `G4BGGNucleonElasticXS` /
`G4NucleonNuclearCrossSection::GetElasticCrossSection`, and the Geant4 Software License notice is
recorded." (Geant4 Software License, see THIRD_PARTY_NOTICES.md; no Geant4 code is copied.)

Formulas (Geant4 11.4.2, files pinned in ``ionmc.data.registry``)
-----------------------------------------------------------------
* ``G4PiData``: energies ``e * GeV``, cross sections in mb, piecewise-linear in E, constant outside
  ``[e_0, e_last]`` and clipped at 0. Proton: sigma_inel = ``p_in`` table; sigma_tot = the NEUTRON
  total table ``m_t`` (``G4ComponentBarNucleonNucleusXsc::LoadData``).
* ``ComputeCrossSections``: for tabulated Z, sigma_tot and sigma_inel at E; otherwise (Z between the
  tabulated Z1 < Z < Z2) ``r_i = x_i A75[Z] / A75[Z_i]`` with ``A75[Z] = aeff[Z]^{2/3}``,
  ``alp1 = aeff[Z] - aeff[Z1]``, ``alp2 = aeff[Z2] - aeff[Z]``,
  ``x = (r1 alp2 + r2 alp1) / (alp1 + alp2)``, applied to sigma_tot and sigma_inel separately;
  sigma_el = max(sigma_tot - sigma_inel, 0).
* ``G4BGGNucleonElasticXS::GetElementCrossSection`` (proton, Z > 1, below the Glauber energy):
  E <= 14 MeV: ``theCoulombFacP[Z] * CoulombFactor(E, Z)`` with ``theCoulombFacP[Z] =
  sigma_el(14 MeV) / CoulombFactor(14 MeV, Z)``; above 14 MeV the Barashenkov value.
* ``G4NuclearRadii::CoulombFactor(Z, A, proton, E)``: ``tR = r0[Z] A^{1/3} fm`` (``RadiusCB``),
  ``pR = 0.895 fm``, ``bC = (alpha hbarc / 2) Z / (pR + tR)``, ``Tcm = sqrt(m_p^2 + M_t^2 + 2 (T +
  m_p) M_t) - m_p - M_t``, factor ``1 - bC / Tcm`` if ``Tcm > bC`` else 0; ``A = lrint(aeff[Z])``.
* p-p (``G4HadronNucleonXsc::HadronNucleonXscNS``, ``G4BGGNucleonElasticXS`` Z = 1): for
  ``p_lab < 0.73 GeV/c`` sigma = ``1.0115 (23 + 50 sqrt(ln(0.73/p)^7))`` mb.
"""

