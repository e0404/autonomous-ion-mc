BARASHENKOV_ENERGY_GEV = {6: _E1_GEV, 7: _E2_GEV, 8: _E2_GEV, 13: _E3_GEV, 14: _E3_GEV, 20: _E3_GEV}
BARASHENKOV_M_T = {6: _C_M_T, 7: _N_M_T, 8: _O_M_T, 13: _AL_M_T, 14: _SI_M_T, 20: _CA_M_T}
BARASHENKOV_P_IN = {6: _C_P_IN, 7: _N_P_IN, 8: _O_P_IN, 13: _AL_P_IN, 14: _SI_P_IN, 20: _CA_P_IN}
TABULATED_Z = (6, 7, 8, 13, 14, 20)
"""Tabulated Z of ``G4ComponentBarNucleonNucleusXsc::theZ`` that this module carries (the table
also has 2, 4, 11, 26, ...; the targets of the nuclear table need only these and the neighbours of
Z = 15)."""
AEFF = {6: 12.0107, 7: 14.0068, 8: 15.9994, 13: 26.9815, 14: 28.0854, 15: 30.9738, 20: 40.078}
"""``aeff[Z]`` of ``G4IsotopeList.hh`` (effective atomic masses, g/mol)."""
R0_CB = {6: 1.54, 7: 1.65, 8: 1.71, 13: 1.53, 14: 1.4, 15: 1.3, 20: 1.4}
"""``G4NuclearRadii::r0[Z]`` (fm) used by ``RadiusCB``."""
SUPPORTED_Z = (6, 7, 8, 13, 14, 15, 20)


class BggError(ValueError):
    """Unsupported element or energy of the BGG elastic cross section (fail closed)."""


def mass_number(z: int) -> int:
    """``theA[Z] = lrint(aeff[Z])`` of ``G4BGGNucleonElasticXS::Initialise``."""
    return int(round(AEFF[z]))


def _table(values: tuple[float, ...] | tuple[int, ...]) -> NDArray[np.float64]:
    return np.asarray(values, dtype=np.float64)


def piecewise_linear_mb(energy_mev: float, z: int, which: str) -> float:
    """``G4PiData`` evaluation: ``which`` = ``"tot"`` (neutron total) or ``"inel"`` (proton
    reaction) of a TABULATED ``z`` at ``energy_mev``."""
    e = _table(BARASHENKOV_ENERGY_GEV[z]) * GEV_MEV
    y = _table(BARASHENKOV_M_T[z] if which == "tot" else BARASHENKOV_P_IN[z])
    if energy_mev <= e[0]:
        return float(y[0])
    if energy_mev >= e[-1]:
        return float(y[-1])
    i = int(np.searchsorted(e, energy_mev, side="left"))  # first node >= E (G4PiData loop)
    return max(
        0.0, float(y[i - 1] + (energy_mev - e[i - 1]) * (y[i] - y[i - 1]) / (e[i] - e[i - 1]))
    )


def barashenkov_mb(energy_mev: float, z: int) -> tuple[float, float]:
    """``(sigma_tot(n+A), sigma_inel(p+A))`` [mb] of ``ComputeCrossSections`` including the
    A^{2/3} interpolation in Z for an untabulated ``z`` (``z`` must be in :data:`SUPPORTED_Z`)."""
    if z not in SUPPORTED_Z:
        raise BggError(f"element Z={z} is not carried by the BGG elastic module")
    if z in TABULATED_Z:
        return piecewise_linear_mb(energy_mev, z, "tot"), piecewise_linear_mb(energy_mev, z, "inel")
    z1 = max(t for t in TABULATED_Z if t < z)
    z2 = min(t for t in TABULATED_Z if t > z)
    out = []
    for which in ("tot", "inel"):
        x1 = piecewise_linear_mb(energy_mev, z1, which)
        x2 = piecewise_linear_mb(energy_mev, z2, which)
        a75 = AEFF[z] ** (2.0 / 3.0)
        r1 = x1 * a75 / AEFF[z1] ** (2.0 / 3.0)
        r2 = x2 * a75 / AEFF[z2] ** (2.0 / 3.0)
        alp1 = AEFF[z] - AEFF[z1]
        alp2 = AEFF[z2] - AEFF[z]
        out.append((r1 * alp2 + r2 * alp1) / (alp1 + alp2))
    return out[0], out[1]


def barashenkov_elastic_mb(energy_mev: float, z: int) -> float:
    """``max(sigma_tot(n+A) - sigma_inel(p+A), 0)`` [mb] (valid at any energy; the BGG low-energy
    rule is :func:`bgg_elastic_mb`)."""
    tot, inel = barashenkov_mb(energy_mev, z)
    return max(tot - inel, 0.0)


def nuclear_mass_mev(z: int) -> float:
    """Nuclear mass [MeV] of ``G4NucleiProperties::GetNuclearMass(A, Z)`` approximated as
    ``A u - Z m_e`` when the caller does not pass the AME2020 mass. The neglected mass excess
    (up to -35 MeV for Ca-40, i.e. 2e-3 relative) shifts the Coulomb factor by < 1e-5 above 14 MeV
    and by up to 3e-4 relative close to the barrier below 14 MeV; the table builder passes the
    AME2020 nuclear mass of the target, so the tables do not use this approximation."""
    a = mass_number(z)
    return a * AMU_MEV - z * M_ELECTRON_MEV


def coulomb_factor(energy_mev: float, z: int, target_mass_mev: float | None = None) -> float:
    """``G4NuclearRadii::CoulombFactor(Z, A, proton, E)`` (module docstring)."""
    a = mass_number(z)
    t_r = R0_CB[z] * a ** (1.0 / 3.0)
    p_r = 0.895
    t_m = nuclear_mass_mev(z) if target_mass_mev is None else target_mass_mev
    tcm = (
        math.sqrt(M_PROTON_MEV**2 + t_m**2 + 2.0 * (energy_mev + M_PROTON_MEV) * t_m)
        - M_PROTON_MEV
        - t_m
    )
    b_c = 0.5 * FINE_STRUCTURE * HBARC_MEV_FM * z / (p_r + t_r)
    return 1.0 - b_c / tcm if tcm > b_c else 0.0


def bgg_elastic_mb(energy_mev: float, z: int, target_mass_mev: float | None = None) -> float:
    """BGG proton elastic cross section [mb] of element ``z`` (> 1) for 0 < E <= 250 MeV."""
    if not 0.0 < energy_mev <= BGG_DOMAIN_MAX_MEV:
        raise BggError(f"energy {energy_mev} MeV outside (0, {BGG_DOMAIN_MAX_MEV}] MeV")
    if energy_mev <= BGG_LOW_ENERGY_MEV:
        fac = barashenkov_elastic_mb(BGG_LOW_ENERGY_MEV, z) / coulomb_factor(
            BGG_LOW_ENERGY_MEV, z, target_mass_mev
        )
        return fac * coulomb_factor(energy_mev, z, target_mass_mev)
    return barashenkov_elastic_mb(energy_mev, z)


def p_lab_gev(t_mev: float) -> float:
    """Laboratory momentum [GeV/c] of a proton of kinetic energy ``t_mev``."""
    return math.sqrt(t_mev * t_mev + 2.0 * M_PROTON_MEV * t_mev) / GEV_MEV


def pp_bgg_mb(t_mev: float) -> float:
    """BGG p-p elastic cross section ``1.0115 (23 + 50 sqrt(ln(0.73/p)^7))`` mb, valid for
    ``p_lab < 0.73 GeV/c`` (T < about 275 MeV); raises :class:`BggError` otherwise."""
    p = p_lab_gev(t_mev)
    if not 0.0 < p < PP_P_LAB_MAX_GEV:
        raise BggError(f"p-p BGG formula needs 0 < p_lab < {PP_P_LAB_MAX_GEV} GeV/c, got {p}")
    return PP_SCALE * (23.0 + 50.0 * math.sqrt(math.log(PP_P_LAB_MAX_GEV / p) ** 7))
