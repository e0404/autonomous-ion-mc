# report


def _identity(doc: Doc) -> list[str]:
    code = doc["provenance"]["code"]
    dirty = code.get("git_dirty")
    return [
        "## Identity",
        "",
        f"- schema: {doc['schema']} {doc['schema_version']} (kind: {doc['kind']})",
        f"- code version: {_txt(code.get('ionmc_version'))}",
        f"- package tree object id: {_txt(code.get('package_tree_oid') or 'unknown')}",
        f"- commit: {_txt(code.get('git_commit') or 'unknown')}",
        f"- dirty: {'unknown' if dirty is None else _f(dirty)}",
        f"- code identity status: {_txt(code.get('status'))}"
        + (f" ({_txt(code['reason'])})" if code.get("reason") else ""),
        "",
    ]


def _validity(doc: Doc) -> list[str]:
    acc = doc["accounting"]
    if doc["valid"]:
        head = "**Result status: valid** (no transport-limit counter is nonzero)."
    else:
        head = (
            "**INVALID RESULT: transport-limit counters are nonzero; arrays are not "
            "physically meaningful.**"
        )
    out = ["## Validity", "", head, ""]
    if acc["reasons"]:
        out += [f"- invalidating counter: {_txt(r)}" for r in acc["reasons"]] + [""]
    return out


def _requested_effective(doc: Doc) -> list[str]:
    extra = doc["effective_extra"]
    rows = []
    for r in extra["resolutions"]:
        req = "; ".join(f"{p} = {_value(_requested_value(doc, p))}" for p in r["requested"])
        eff = "; ".join(f"{p} = {_value(_effective_value(doc, p))}" for p in r["effective"])
        rows.append((r["row"], r["class"], r["rule"], req or "-", eff or "-", r["reason"] or "-"))
    out = [
        "## Requested versus effective configuration",
        "",
        f"Resolution status: {_txt(extra['resolutions_status'])}. Classes: equal, derived, "
        "unused, requested-only (decision 0045 section 4).",
        "",
    ]
    if rows:
        out += _table(("row", "class", "rule", "requested", "effective", "reason"), rows)
    else:
        out.append("No resolution rows are recorded.")
    return [*out, ""]


def _source_geometry(doc: Doc) -> list[str]:
    eff, extra, man = doc["effective"], doc["effective_extra"], doc["input_manifest"]
    src = eff["source"]
    out = ["## Source, geometry and materials", ""]
    out.append("- source: " + ", ".join(f"{k} = {_f(src[k])}" for k in sorted(src)))
    out.append(f"- source unit direction: {_f(eff['unit_direction'])}")
    geo = eff["geometry"]
    out.append(
        f"- geometry: origin {_f(geo['origin_mm'])} mm, spacing {_f(geo['spacing_mm'])} mm, shape "
        f"{_f(geo['shape'])}, materials {_f(geo['materials'])}, "
        f"exit plane z = {_f(geo['z_exit_mm'])}"
    )
    out.append(f"- grid convention: {_txt(extra['grid_convention'])}")
    pa = int(extra["profile_axis"])
    out.append(
        f"- profile axis: {pa} ({_AXES[pa]}), the grid axis of the largest absolute component "
        "of the source unit direction"
    )
    for s in eff["scoring"]:
        out.append(
            f"- scoring grid {_txt(s['name'])}: origin {_f(s['origin_mm'])} mm, spacing "
            f"{_f(s['spacing_mm'])} mm, shape {_f(s['shape'])}"
        )
    out += ["", "Input files (basename and sha256 only):", ""]
    cf = man["config_file"]
    cfg_sha = cf.get("sha256") if isinstance(cf, Mapping) else None
    out.append(
        f"- manifest source: {_txt(man['source'])}; configuration sha256: {man['config_sha256']}"
    )
    if man["source"] == "toml" and isinstance(cf, Mapping):
        out.append(f"- configuration file: {_txt(_basename(cf.get('path')))} sha256 {_f(cfg_sha)}")
    for f in man["files"]:
        out.append(
            f"- input file ({_txt(f['role'])}): {_txt(_basename(f['path']))} "
            f"sha256 {_f(f['sha256'])}"
        )
    if not man["files"]:
        out.append("- no referenced input files")
    out += ["", "Materials:", ""]
    rows = []
    for m in extra["materials"]:
        i_ev = f"{_f(m['I_eV_requested'])} / {_f(m['I_eV_effective'])}"
        rows.append((m["name"], m["density_g_cm3"], i_ev, _f(m["mass_fractions"]), m["source"]))
    head = ("name", "density g/cm3", "I eV requested / effective", "mass fractions", "source")
    out += _table(head, rows)
    return [*out, ""]


def _evidence(rec: Mapping[str, Any]) -> list[str]:
    body = json.dumps(rec, sort_keys=True, ensure_ascii=True, separators=(", ", ": "))
    out = [EVIDENCE_FENCE, body, "```"]
    if str(rec.get("status", "")).startswith("topas-agreement-shared-lineage:"):
        out += ["", SHARED_LINEAGE_NOTE]
    return out


def _physics(doc: Doc) -> list[str]:
    ph, models = doc["effective"]["physics"], doc["provenance"]["models"]
    st = doc["effective"].get("stopping") or {}
    out = ["## Physics and stopping model", ""]
    out.append("- physics options: " + ", ".join(f"{k} = {_f(ph[k])}" for k in sorted(ph)))
    out.append(
        f"- stopping model: requested {_txt(st.get('model_id_requested'))}, effective "
        f"{_txt(models['stopping_model_id_effective'])}, version "
        f"{_txt(models['stopping_version'])}, spec sha256 {_f(models['stopping_spec_sha256'])}"
    )
    out.append(
        f"- stopping kind: {_txt(st.get('kind'))}; interpolation: "
        f"{_txt(st.get('interpolation'))}; range construction: "
        f"{_txt(st.get('range_construction'))}"
    )
    out.append(
        f"- straggling: {_f(models['straggling_model'])}; multiple scattering: "
        f"{_f(models['mcs_model'])}; end of range: {_f(models['end_of_range_model'])}; delta "
        f"electrons: {_f(models['delta_electrons'])}; nuclear table: "
        f"{_f(models['nuclear_table_id'])}"
    )
    out += [
        "",
        "Stopping-evidence records at run time (verbatim, as persisted; never recomputed):",
        "",
    ]
    recs = models["evidence_at_run"] or []
    for rec in recs:
        out += [*_evidence(rec), ""]
    if not recs:
        out += ["No evidence record is persisted for this model.", ""]
    return out


def _data(doc: Doc) -> list[str]:
    d = doc["provenance"]["data"]
    out = ["## Data identities and roles", ""]
    for u in d["stopping_data_used"]:
        pin = u.get("pin", {})
        keys = ("dataset_id", "archive_sha256", "member", "license", "licence", "parser")
        pin_s = ", ".join(f"{k} = {_f(pin[k])}" for k in keys if pin.get(k) is not None)
        out.append(
            f"- stopping dataset ({_txt(u.get('role_in_this_run'))}): {_txt(pin_s)}; "
            f"table {_f(u.get('table'))}"
        )
    if not d["stopping_data_used"]:
        out.append("- stopping data used: none (analytic model)")
    out.append(f"- stopping data content sha256: {_f(d['stopping_content_sha256'])}")
    out.append(
        f"- table sha256: {_f(d['table_sha256'])}; table stopping source: "
        f"{_txt(d['table_stopping_source'])}"
    )
    for m in d["table_materials"]:
        out.append(
            f"- table material {_txt(m['material'])} ({_txt(m['projectile'])}): source "
            f"{_txt(m['source'])}, dataset {_f(m['dataset_id'])}, content sha256 "
            f"{_f(m['content_sha256'])}"
        )
    nuc = d.get("nuclear")
    if nuc:
        out.append(f"- nuclear table {_txt(nuc['table_id'])}: npz sha256 {_f(nuc['npz_sha256'])}")
    for lk in d["lookups"]:
        out.append(
            f"- user lookup {_txt(lk['name'])} ({_txt(lk['quantity'])}, {_txt(lk['units'])}): "
            f"content sha256 {_f(lk['content_sha256'])}, file sha256 "
            f"{_f(lk.get('file_sha256'))}; values are not persisted"
        )
    return [*out, ""]


def _run(doc: Doc) -> list[str]:
    r = doc["run"]
    rng = r["rng"]
    out = ["## Run and random numbers", ""]
    out.append(
        f"- backend: {_txt(r['backend'])}, device: {_txt(r['device'])}, precision: "
        f"{_txt(r['precision'])}, production: {_f(r['production'])}"
    )
    out.append(f"- seed: {r['seed']}; histories: {r['n_histories']} in {r['n_batches']} batches "
               f"({r['histories_per_batch']} per batch); cpu workers: {r['cpu_workers']}; "
               f"chunk histories: {r['chunk_histories']}")  # fmt: skip
    out.append("- random numbers: " + ", ".join(f"{k} = {_txt(rng[k])}" for k in sorted(rng)))
    out.append(
        "- timings are recorded in result.json only (not deterministic) and are not printed here"
    )
    return [*out, ""]


def _statistics(doc: Doc) -> list[str]:
    st = doc["statistics"]
    out = ["## Statistics definition", ""]
    for k in ("normalisation", "uncertainty", "defined_mask", "sparse_mask"):
        out.append(f"- {k}: {_txt(st[k])}")
    out.append(f"- batch arrays: {_f(st['batch_arrays'])}")
    out.append(f"- quantity batch arrays: {_f(st['quantity_batch_arrays'])}")
    return [*out, ""]


def _grids(doc: Doc, arrays: Arrays) -> list[str]:
    out = ["## Per-grid summary", ""]
    for g in doc["statistics"]["grids"]:
        name = str(g["name"])
        out.append(f"### Grid {_txt(name)}")
        out.append("")
        out.append(
            f"- shape: {_f(g['shape'])}; valid: {_f(g['valid'])}; low batch count: "
            f"{_f(g['low_batch_count'])}"
        )
        out.append(
            f"- defined voxels: {g['n_defined_voxels']}; sparse voxels: {g['n_sparse_voxels']}"
        )
        out.append(f"- total energy per history: {_f(g['energy_total_mev'])}")
        out.append(f"- maximum dose per history: {_f(g['dose_max_gy'])}")
        out.append(
            f"- maximum relative uncertainty (defined voxels): {_f(g['relative_uncertainty_max'])}"
        )
        dose, mask = (
            _find(doc, arrays, "grid", name, "dose_gy"),
            _find(doc, arrays, "grid", name, "defined_mask"),
        )
        if dose is not None and mask is not None:
            pk = _peak(dose, mask)
            out.append(
                f"- voxel of maximum dose (indices): {'undefined' if pk is None else _f(list(pk))}"
            )
        for e in doc["arrays"]:
            o = e["origin"]
            if (
                o.get("kind") == "quantity"
                and o.get("grid") == name
                and o.get("array") == "defined_mask"
            ):
                m = np.asarray(arrays[e["name"]], dtype=bool)
                out.append(
                    f"- tally {_txt(o['name'])} ({_txt(o['quantity'])}): defined voxels "
                    f"{int(m.sum())} of {m.size}"
                )
        out.append("")
    return out


def _accounting(doc: Doc) -> list[str]:
    acc = doc["accounting"]
    eb = acc["energy_balance"]
    out = ["## Energy balance and counters", ""]
    for k in sorted(eb):
        if k == "nuclear_mev":
            out += [f"- nuclear {n}: {_f(v)} MeV" for n, v in sorted(eb[k].items())]
        else:
            out.append(f"- {k}: {_f(eb[k])}" + (" MeV" if k.endswith("_mev") else ""))
    out += [f"- counter {k}: {v}" for k, v in sorted(acc["counters"].items())]
    out += [f"- channel counter {k}: {v}" for k, v in sorted(acc["channel_counters"].items())]
    return [*out, ""]


def _missing(doc: Doc) -> list[str]:
    st, man, extra = doc["statistics"], doc["input_manifest"], doc["effective_extra"]
    items: list[str] = []
    if st["batch_arrays"].get("status") != "persisted":
        items.append(f"batch arrays: {_f(st['batch_arrays'])}")
    if st["quantity_batch_arrays"].get("status") != "persisted" and st["quantity_batch_arrays"].get(
        "reason"
    ):
        items.append(f"quantity batch arrays: {_f(st['quantity_batch_arrays'])}")
    for g in st["grids"]:
        for k in ("dose_max_gy", "relative_uncertainty_max"):
            if g[k].get("status") == "undefined":
                items.append(
                    f"grid {g['name']}: {k} undefined "
                    f"({g[k].get('reason') or 'no reason recorded'})"
                )
    if man["source"] == "api":
        items.append("input files and configuration file: constructed in process (unavailable)")
    stopping = doc["requested"].get("physics", {}).get("stopping")
    if isinstance(stopping, Mapping) and stopping.get("reconstructible") is False:
        items.append("stopping object supplied by the API: not reconstructible from the bundle")
    if doc["provenance"]["data"]["lookups"]:
        items.append("user lookup tables: identities only; values are never persisted")
    items.append(
        "stopping, range, LET-water and nuclear table values: identities only; "
        "values are never persisted"
    )
    if not extra["resolutions"]:
        items.append(f"resolutions: {_f(extra['resolutions_status'])}")
    return ["## Missing items", "", *[f"- {_txt(i)}" for i in items], ""]


def render_report(doc: Doc, arrays: Arrays) -> str:
    """The Markdown report; the last line is "Not a clinical claim."."""
    lines: list[str] = ["# ionmc result report", ""]
    lines += _identity(doc)
    lines += _validity(doc)
    lines += _requested_effective(doc)
    lines += _source_geometry(doc)
    lines += _physics(doc)
    lines += _data(doc)
    lines += _run(doc)
    lines += _statistics(doc)
    lines += _grids(doc, arrays)
    lines += _accounting(doc)
    lines += _missing(doc)
    lines += [LAST_LINE]
    return "\n".join(lines) + "\n"


def render_all(doc: Doc, arrays: Arrays) -> dict[str, str]:
    """Every derived file of a bundle: ``report.md`` and ``plots/*.svg``."""
    return {"report.md": render_report(doc, arrays), **render_plots(doc, arrays)}


def regenerate_report(bundle: str | Path, **budgets: int) -> dict[str, bytes]:
    """Load ``bundle`` (tier 1: every hash and invariant checked; ``budgets`` are the keyword
    budgets of :func:`ionmc.results.load`) and return the bytes of ``report.md`` and every
    ``plots/*.svg`` as the writer produces them."""
    from ionmc.results import load

    loaded = load(bundle, **budgets)
    return {n: t.encode("utf-8") for n, t in render_all(loaded.doc, loaded.arrays).items()}
