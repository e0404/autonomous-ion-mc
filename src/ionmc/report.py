"""Human-readable report and SVG profiles of a result bundle (decision 0045 section 5).

``render_report`` and ``render_plots`` are PURE functions of the bundle content: the ``result.json``
document (the ``files`` block is ignored) and the catalogue arrays. ``results.save`` calls them to
write ``report.md`` and ``plots/*.svg``; :func:`regenerate_report` loads a bundle (tier 1) and calls
them again, so the regenerated bytes equal the written ones.

The report never prints a timing or a value of the path set P (decision 0045 section 2): input
files appear by basename and sha256, caches by dataset id. Stopping-evidence records are copied
verbatim from ``provenance.models.evidence_at_run`` (never paraphrased, never recomputed); the
text generated here never uses the word that decision 0044 reserves. Not a clinical claim.
"""

from __future__ import annotations

import json
import math
import re
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

import numpy as np

from ionmc import svg

Arrays = Mapping[str, "np.ndarray[Any, Any]"]
Doc = Mapping[str, Any]

LAST_LINE = "Not a clinical claim."
SHARED_LINEAGE_NOTE = "shared stopping-data lineage; transport agreement only"
EVIDENCE_FENCE = "```evidence"
_RESERVED = re.compile(r"\bvalidated\b")
_PATHLIKE = re.compile(r"(?<![\w.])/[\w.\-]+(?:/[\w.\-]+)+|[A-Za-z]:\\[\w.\\\-]+")
_AXES = "xyz"
_LET_QUANTITIES = ("let_d", "let_t")
_VALUE_WIDTH = 70


# ---------------------------------------------------------------------------------------------
# formatting


def _f(v: Any) -> str:
    """One deterministic text form of a JSON value (floats with ``.6g``)."""
    if v is None:
        return "undefined"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return format(v, ".6g") if math.isfinite(v) else "undefined"
    if isinstance(v, str):
        return v
    if isinstance(v, Mapping):
        if "value" in v and set(v) <= {"value", "units", "status", "reason"}:  # a scalar record
            if v["value"] is None:
                return "undefined" + (f" ({v['reason']})" if v.get("reason") else "")
            return f"{_f(v['value'])} {v['units']}"
        return "{" + ", ".join(f"{k}: {_f(v[k])}" for k in sorted(v)) + "}"
    if isinstance(v, Sequence):
        return "[" + ", ".join(_f(x) for x in v) + "]"
    return str(v)


def _txt(s: Any) -> str:
    """Free text of the document in a Markdown line: one line, the reserved word withheld."""
    t = _RESERVED.sub("(word withheld)", " ".join(str(s).split()))
    return t


def _cell(s: Any) -> str:
    return _txt(s).replace("|", "\\|")


def _value(v: Any) -> str:
    t = _PATHLIKE.sub("<path>", _f(v))
    return t if len(t) <= _VALUE_WIDTH else t[: _VALUE_WIDTH - 3] + "..."


def _basename(p: Any) -> str:
    if not isinstance(p, str):
        return "unavailable"
    return p.replace("\\", "/").rsplit("/", 1)[-1]


def _table(head: Sequence[str], rows: Sequence[Sequence[Any]]) -> list[str]:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(_cell(c) for c in r) + " |" for r in rows]
    return out


def _requested_value(doc: Doc, path: str) -> Any:
    cur: Any = doc["requested"]
    for part in path.split("."):
        if not isinstance(cur, Mapping) or part not in cur:
            return "not given"
        cur = cur[part]
    return cur


def _effective_value(doc: Doc, pointer: str) -> Any:
    cur: Any = doc["effective"]
    for part in pointer.strip("/").split("/"):
        if isinstance(cur, Mapping) and part in cur:
            cur = cur[part]
        else:
            return "not present"
    return cur


# ---------------------------------------------------------------------------------------------
# catalogue access (pure functions of the document and the arrays)


def _find(doc: Doc, arrays: Arrays, kind: str, grid: str | None, array: str,
          quantity_index: int | None = None) -> np.ndarray[Any, Any] | None:  # fmt: skip
    for e in doc["arrays"]:
        o = e["origin"]
        if o.get("kind") != kind or o.get("array") != array or o.get("grid") != grid:
            continue
        if quantity_index is not None and o.get("index") != quantity_index:
            continue
        return arrays[e["name"]]
    return None


def _grid_names(doc: Doc) -> list[str]:
    return [str(g["name"]) for g in doc["statistics"]["grids"]]


def _scoring(doc: Doc, name: str) -> Mapping[str, Any]:
    for s in doc["effective"]["scoring"]:
        if s["name"] == name:
            return s  # type: ignore[no-any-return]
    raise KeyError(name)


def _safe_member_parts(doc: Doc) -> dict[str, str]:
    """grid name -> the safe name used in its catalogue members (``grid__<safe>__...``)."""
    out: dict[str, str] = {}
    for e in doc["arrays"]:
        m = re.fullmatch(r"grid__([a-z0-9_-]+?)__(?:q__.*|[a-z_]+)", e["name"])
        if m and e["origin"].get("kind") in ("grid", "quantity"):
            out.setdefault(str(e["origin"]["grid"]), m.group(1))
    return out


def _quantity_safe(doc: Doc, grid: str, index: int) -> str:
    for e in doc["arrays"]:
        o = e["origin"]
        if o.get("kind") == "quantity" and o.get("grid") == grid and o.get("index") == index:
            m = re.fullmatch(r"grid__.+?__q__(.+)__(?:mean|std|defined_mask|n_nonzero|"
                             r"rounding_bound|batch_num|batch_den)", e["name"])  # fmt: skip
            if m:
                return m.group(1)
    return f"q{index}"


def _peak(dose: np.ndarray[Any, Any], mask: np.ndarray[Any, Any]) -> tuple[int, ...] | None:
    ok = np.asarray(mask, dtype=bool) & np.isfinite(dose)
    if not ok.any():
        return None
    flat = np.where(ok, dose, -np.inf)
    return tuple(int(i) for i in np.unravel_index(int(np.argmax(flat)), dose.shape))


def _coords(sc: Mapping[str, Any], axis: int) -> list[float]:
    o, d, n = float(sc["origin_mm"][axis]), float(sc["spacing_mm"][axis]), int(sc["shape"][axis])
    return [o + (i + 0.5) * d for i in range(n)]  # voxel centres (decision 0037)


def _line_through(a: np.ndarray[Any, Any], index: Sequence[int], axis: int) -> np.ndarray[Any, Any]:
    sel: list[Any] = list(index)
    sel[axis] = slice(None)
    return np.asarray(a[tuple(sel)], dtype=np.float64)


def _lateral_axis(axis: int) -> int:
    return next(a for a in range(3) if a != axis)


# ---------------------------------------------------------------------------------------------
# plots


def render_plots(doc: Doc, arrays: Arrays) -> dict[str, str]:
    """``{"plots/<safe>.svg": svg text}`` for every grid (depth dose with a 1-sigma band,
    depth-integrated energy, one lateral profile at the depth of maximum) and every LET tally."""
    axis = int(doc["effective_extra"]["profile_axis"])
    lat = _lateral_axis(axis)
    ax_name, lat_name = _AXES[axis], _AXES[lat]
    safe = _safe_member_parts(doc)
    used: set[str] = set()
    out: dict[str, str] = {}

    def put(raw: str, text: str) -> None:
        from ionmc.results import safe_name

        out[f"plots/{safe_name(raw, used, 64)}.svg"] = text

    for g in _grid_names(doc):
        gs = safe.get(g, "x")
        sc = _scoring(doc, g)
        dose = _find(doc, arrays, "grid", g, "dose_gy")
        std = _find(doc, arrays, "grid", g, "dose_std_gy")
        energy = _find(doc, arrays, "grid", g, "energy_mev")
        mask = _find(doc, arrays, "grid", g, "defined_mask")
        if dose is None or std is None or energy is None or mask is None:
            continue
        want = tuple(int(n) for n in sc["shape"])
        if any(np.shape(x) != want for x in (dose, std, energy, mask)):
            continue  # inconsistent arrays: no plot (the reader refuses such a bundle)
        defined = np.asarray(mask, dtype=bool)
        peak = _peak(dose, defined)
        centre = tuple(n // 2 for n in dose.shape)
        where = peak if peak is not None else centre
        loc = (f"column through the voxel of maximum dose (indices {_f(list(where))})"
               if peak is not None else "no voxel has a defined dose")  # fmt: skip
        z = _coords(sc, axis)
        d = np.where(defined, dose, np.nan)
        s = np.where(defined, std, np.nan)
        d_line = _line_through(d, where, axis)
        s_line = _line_through(s, where, axis)
        fig = svg.Figure(f"Depth dose profile, grid {g}", f"{ax_name} (mm), profile axis",
                         "dose per history (Gy)", f"{loc}; band = +-1 standard error")  # fmt: skip
        fig.band(z, d_line - s_line, d_line + s_line)  # the actual +-1 SE band, never clipped
        fig.line("dose", z, d_line)
        put(f"dose__{gs}", fig.render())

        others = tuple(a for a in range(3) if a != axis)
        e_prof = np.asarray(energy, dtype=np.float64).sum(axis=others)
        fig = svg.Figure(f"Depth-integrated energy profile, grid {g}",
                         f"{ax_name} (mm), profile axis", "energy per history (MeV)",
                         "sum over the two lateral axes")  # fmt: skip
        fig.line("energy", z, e_prof)
        put(f"energy__{gs}", fig.render())

        y = _coords(sc, lat)
        l_d = _line_through(d, where, lat)
        l_s = _line_through(s, where, lat)
        note = f"along {lat_name} at the depth of maximum dose; band = +-1 standard error"
        fig = svg.Figure(
            f"Lateral dose profile, grid {g}", f"{lat_name} (mm)", "dose per history (Gy)", note
        )
        fig.band(y, l_d - l_s, l_d + l_s)
        fig.line("dose", y, l_d)
        put(f"lateral__{gs}", fig.render())

        for e in doc["arrays"]:
            o = e["origin"]
            is_let = o.get("kind") == "quantity" and o.get("quantity") in _LET_QUANTITIES
            if not (is_let and o.get("grid") == g and o.get("array") == "mean"):
                continue
            qi = int(o["index"])
            mean = arrays[e["name"]]
            qmask = _find(doc, arrays, "quantity", g, "defined_mask", qi)
            if mean.ndim != 3 or qmask is None:
                continue  # a spectrum-shaped quantity is not a LET profile
            vals = np.where(np.asarray(qmask, dtype=bool), mean, np.nan)
            fig = svg.Figure(
                f"{o['quantity']} depth profile, grid {g}, tally {o['name']}",
                f"{ax_name} (mm), profile axis",
                f"{o['quantity']} ({e['units']})",
                "column through the voxel of maximum dose; undefined voxels are gaps",
            )
            fig.line(str(o["quantity"]), z, _line_through(vals, where, axis))
            put(f"let__{gs}__{_quantity_safe(doc, g, qi)}", fig.render())
    return out


